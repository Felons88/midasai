// Nexus Node Registry — production node definitions
// Every node has: metadata, icon, category, inputs, outputs, config schema, validation, execution impl key

export type NodeCategory =
  | "ai" | "llm" | "image" | "audio" | "developer" | "database"
  | "cloud" | "logic" | "files" | "midas" | "analytics" | "browser"
  | "ide" | "communication" | "data" | "devops" | "finance" | "crm" | "utility"
  | "marketing" | "productivity"

export type FieldType =
  | "string" | "number" | "boolean" | "select" | "multiselect"
  | "textarea" | "json" | "code" | "secret" | "url" | "file" | "credential"

export interface NodeField {
  key: string
  label: string
  type: FieldType
  required?: boolean
  default?: unknown
  options?: { label: string; value: string; icon?: string }[]
  placeholder?: string
  description?: string
  group?: string
  showIf?: Record<string, unknown>
  validate?: (v: unknown) => string | null
  credentialProvider?: string
}

export interface NodePort {
  id: string
  label: string
  type: "any" | "string" | "number" | "boolean" | "object" | "array" | "trigger"
  required?: boolean
}

export interface NodeDefinition {
  id: string
  name: string
  description: string
  category: NodeCategory
  /** SVG path or URL or brand color letter */
  icon: string
  /** Hex brand color */
  color: string
  inputs: NodePort[]
  outputs: NodePort[]
  credentials?: string[]
  fields: NodeField[]
  /** Server-side executor key */
  executor: string
  docs?: string
  tags?: string[]
  premium?: boolean
  
  // n8n Compatibility Fields
  /** All n8n node types that map to this node */
  n8nAliases?: string[]
  /** Minimum n8n version required */
  n8nVersion?: string
  /** Function to convert n8n config to Nexus config */
  importMapper?: (n8nConfig: Record<string, unknown>) => Record<string, unknown>
  /** Function to convert Nexus config to n8n config */
  exportMapper?: (nexusConfig: Record<string, unknown>) => Record<string, unknown>
  /** Validation rules for configuration */
  validationRules?: ValidationRule[]
}

export interface ValidationRule {
  field: string
  rule: 'required' | 'pattern' | 'min' | 'max' | 'custom'
  value?: string | number
  message: string
  customValidate?: (v: unknown) => boolean
}

const T = (id: string, label: string): NodePort => ({ id, label, type: "trigger" })
const D = (id: string, label: string, type: NodePort["type"] = "any"): NodePort => ({ id, label, type })

